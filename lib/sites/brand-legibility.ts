import { colorContrast, readableColorText } from "@/lib/branding/color-contrast";

function hex(value:string): string | null {
  if(/^#[\da-f]{6}$/i.test(value)) return value;
  if(/^#[\da-f]{3}$/i.test(value)) return `#${value.slice(1).split("").map(c=>c+c).join("")}`;
  return null;
}

function blend(first:string,second:string,weight:number):string {
  return `#${[1,3,5].map(index=>Math.round(parseInt(first.slice(index,index+2),16)*weight+parseInt(second.slice(index,index+2),16)*(1-weight)).toString(16).padStart(2,"0")).join("")}`;
}

/** Resolve only the opaque RGB colors and color-mixes generated by the editor.
 * Advanced CSS remains the operator's responsibility. Never evaluates CSS. */
function color(value:string|undefined,tokens:Record<string,string>,depth=0):string|null {
  if(!value || depth>5) return null;
  const direct=hex(value.trim()); if(direct) return direct;
  const variable=/^var\((--site-[\w-]+)\)$/.exec(value);
  if(variable) return color(tokens[variable[1]],tokens,depth+1);
  const mix=/^color-mix\(in srgb,\s*(.+)\s+(\d+(?:\.\d+)?)%,\s*(.+)\)$/.exec(value);
  if(!mix) return null;
  const first=color(mix[1],tokens,depth+1),second=color(mix[3],tokens,depth+1),weight=Number(mix[2])/100;
  if(!first || !second || weight<0 || weight>1) return null;
  return blend(first,second,weight);
}

export function siteBrandLegibility(tokens:Record<string,string>):Record<string,string> {
  const result:Record<string,string>={};
  const roles=[
    ["ink","--site-ink","#FFFFFF","--site-accent"],
    ["ink-strong","--site-ink-strong","#FFFFFF","--site-accent"],
    ["canvas","--site-canvas","--site-ink","--site-gold"],
    ["canvas-alt","--site-canvas-alt","--site-ink","--site-gold"],
    ["surface","--site-surface","--site-ink","--site-gold"],
    ["accent","--site-accent","--site-accent-ink","--site-accent-ink"],
  ];
  for(const [name,backgroundKey,preferredKey,accentKey] of roles){
    const background=color(tokens[backgroundKey],tokens);
    if(!background) continue;
    const readable=(candidate:string|undefined)=>{
      const preferred=color(candidate,tokens);
      if(preferred && colorContrast(preferred,background)>=4.5) return preferred;
      const target=readableColorText(background);
      if(preferred) for(let step=1;step<=20;step++){
        const adjusted=blend(preferred,target,1-step/20);
        if(colorContrast(adjusted,background)>=4.5) return adjusted;
      }
      return target;
    };
    const preferred=preferredKey.startsWith("--")?tokens[preferredKey]:preferredKey;
    result[`--site-on-${name}`]=readable(preferred);
    result[`--site-on-${name}-accent`]=readable(tokens[accentKey]);
    const primary=result[`--site-on-${name}`];
    result[`--site-on-${name}-body`]=readable(name.startsWith("ink")?blend(primary,background,0.78):tokens["--site-body"]);
    result[`--site-on-${name}-muted`]=readable(name.startsWith("ink")?blend(primary,background,0.55):tokens["--site-muted"]);
  }
  return result;
}
