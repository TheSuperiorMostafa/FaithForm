/** A line's total in cents, or null when the line is included at no charge. */
export function lineTotalCents(line: Pick<InvoiceLineItem, "qty" | "unitCents">): number | null {
  if (line.unitCents === null) return null;
  return line.qty * line.unitCents;
}

/** Churches are tax exempt: the total due is the subtotal. */
export function computeInvoiceTotals(lines: readonly InvoiceLineItem[]): {
  subtotalCents: number;
  totalCents: number;
} {
  const subtotalCents = lines.reduce((sum, line) => sum + (lineTotalCents(line) ?? 0), 0);
  return { subtotalCents, totalCents: subtotalCents };
}

const usd = new Intl.NumberFormat("en-US", {
  style: "currency",
  currency: "USD",
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
});

/** 25000 → "$250.00". */
export function formatCents(cents: number): string {
  return usd.format(cents / 100);
}

/**
 * Parses what a person types as a price ("250", "$1,250.50") into cents.
 * Returns null for anything that is not a non-negative amount with at most
 * two decimal places.
 */
export function parseDollarsToCents(input: string): number | null {
  const cleaned = input.trim().replace(/[$,\s]/g, "");
  if (!/^\d+(\.\d{1,2})?$/.test(cleaned)) return null;
  const [whole, fraction = ""] = cleaned.split(".");
  const cents = Number(whole) * 100 + Number(fraction.padEnd(2, "0"));
  return Number.isSafeInteger(cents) ? cents : null;
}

/** "FFT-1001" style, as generated by the database sequence. */
export function isInvoiceNumber(value: string): boolean {
  return /^FFT-\d{4,}$/.test(value);
}

/** "2026-11" or "2026-11-01" → "2026-11-01"; null if not a real month. */
export function normalizePeriodStart(value: string): string | null {
  const match = /^(\d{4})-(\d{2})(?:-01)?$/.exec(value.trim());
  if (!match) return null;
  const year = Number(match[1]);
  const month = Number(match[2]);
  if (year < 2020 || year > 2100 || month < 1 || month > 12) return null;
  return `${match[1]}-${match[2]}-01`;
}

const MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];
const SHORT_MONTHS = MONTHS.map((month) => month.slice(0, 3));

function dateParts(isoDate: string): { year: number; month: number; day: number } | null {
  const match = /^(\d{4})-(\d{2})-(\d{2})/.exec(isoDate);
  if (!match) return null;
  return { year: Number(match[1]), month: Number(match[2]), day: Number(match[3]) };
}

/** "2026-11-01" → "November 2026". Read as a calendar date, never shifted by time zone. */
export function formatPeriodLabel(periodStart: string): string {
  const parts = dateParts(periodStart);
  if (!parts || parts.month < 1 || parts.month > 12) return periodStart;
  return `${MONTHS[parts.month - 1]} ${parts.year}`;
}

/** "2026-11-03" → "Nov 3, 2026". */
export function formatInvoiceDate(isoDate: string): string {
  const parts = dateParts(isoDate);
  if (!parts || parts.month < 1 || parts.month > 12) return isoDate;
  return `${SHORT_MONTHS[parts.month - 1]} ${parts.day}, ${parts.year}`;
}

/** "2026-11-03" → "November 3, 2026", as printed on the PDF. */
export function formatInvoiceDateLong(isoDate: string): string {
  const parts = dateParts(isoDate);
  if (!parts || parts.month < 1 || parts.month > 12) return isoDate;
  return `${MONTHS[parts.month - 1]} ${parts.day}, ${parts.year}`;
}

/** The current month as YYYY-MM-01 in the given time zone. */
export function currentPeriodStart(now: Date = new Date(), timeZone = "America/New_York"): string {
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone,
    year: "numeric",
    month: "2-digit",
  }).formatToParts(now);
  const year = parts.find((part) => part.type === "year")?.value ?? "1970";
  const month = parts.find((part) => part.type === "month")?.value ?? "01";
  return `${year}-${month}-01`;
}

/** Today as YYYY-MM-DD in the given time zone. */
export function todayIsoDate(now: Date = new Date(), timeZone = "America/New_York"): string {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(now);
}

/**
 * Which status changes an admin may make. Paid and due can be switched back
 * and forth (a payment recorded by mistake); void is final, so a voided month
 * is reissued as a new invoice rather than revived.
 */
export function canChangeInvoiceStatus(from: InvoiceStatus, to: InvoiceStatus): boolean {
  if (from === to) return false;
  if (from === "void") return false;
  return true;
}

