/** "FFT-1001-November-2026.pdf" */
export function invoiceFileName(invoice: Pick<ChurchInvoice, "invoiceNumber" | "periodStart">): string {
  const period = formatPeriodLabel(invoice.periodStart).replace(/\s+/g, "-");
  const safe = `${invoice.invoiceNumber}-${period}`.replace(/[^A-Za-z0-9-]/g, "");
  return `${safe}.pdf`;
}

function text(value: unknown, max: number): string {
  return typeof value === "string" ? value.slice(0, max) : "";
}

/** Reads the stored jsonb line items defensively; bad rows are dropped. */
export function parseStoredLineItems(value: unknown): InvoiceLineItem[] {
  if (!Array.isArray(value)) return [];
  const lines: InvoiceLineItem[] = [];
  for (const raw of value) {
    if (!raw || typeof raw !== "object") continue;
    const row = raw as Record<string, unknown>;
    const qty = Number(row.qty);
    const unit = row.unit_cents;
    lines.push({
      description: text(row.description, 200),
      detail: text(row.detail, 400),
      qty: Number.isInteger(qty) && qty > 0 ? qty : 1,
      unitCents: typeof unit === "number" && Number.isInteger(unit) && unit >= 0 ? unit : null,
    });
  }
  return lines;
}

export function toStoredLineItems(lines: readonly InvoiceLineItem[]) {
  return lines.map((line) => ({
    description: line.description,
    detail: line.detail,
    qty: line.qty,
    unit_cents: line.unitCents,
  }));
}

export function parseStoredBilledTo(value: unknown): BilledTo {
  const row = value && typeof value === "object" ? (value as Record<string, unknown>) : {};
  return {
    organization: text(row.organization, 200),
    contactName: text(row.contact_name, 160),
    email: text(row.email, 254),
    phone: text(row.phone, 40),
  };
}

export function toStoredBilledTo(billedTo: BilledTo) {
  return {
    organization: billedTo.organization,
    contact_name: billedTo.contactName,
    email: billedTo.email,
    phone: billedTo.phone,
  };
}

