#!/usr/bin/env node
/**
 * Generates native design-token constants from design/faithful/tokens.json and
 * verifies every documented contrast pair against WCAG 2.1.
 *
 * Outputs, all committed:
 *   apps/faithful-ios/Sources/FaithfulKit/Generated/DesignTokens.swift
 *   apps/faithful-android/core/design/src/main/kotlin/.../DesignTokens.kt
 *
 * `--check` verifies the committed output is current and re-runs the contrast
 * audit without writing. CI uses it so a token edit that skips regeneration
 * fails rather than letting the two platforms drift apart.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";

const CHECK = process.argv.includes("--check");
const ROOT = process.cwd();
const tokens = JSON.parse(
  readFileSync(join(ROOT, "design/faithful/tokens.json"), "utf8"),
);

const HEADER = [
  "Generated by scripts/generate-design-tokens.mjs — do not edit by hand.",
  "Source of truth: design/faithful/tokens.json",
  "Regenerate with: pnpm design:generate",
];

// ---------------------------------------------------------------------------
// Contrast audit — the tokens are not valid if they are not readable
// ---------------------------------------------------------------------------

function parseHex(hex) {
  const raw = hex.replace("#", "");
  const full = raw.length === 8 ? raw.slice(0, 6) : raw;
  return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16));
}

function relativeLuminance(hex) {
  const channels = parseHex(hex).map((value) => {
    const c = value / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2];
}

function contrastRatio(a, b) {
  const la = relativeLuminance(a);
  const lb = relativeLuminance(b);
  const [light, dark] = la > lb ? [la, lb] : [lb, la];
  return (light + 0.05) / (dark + 0.05);
}

const contrastFailures = [];
for (const theme of ["light", "dark"]) {
  const palette = tokens.color[theme];
  for (const pair of tokens.contrast.pairs) {
    const fg = palette[pair.foreground];
    const bg = palette[pair.background];
    if (!fg || !bg) {
      contrastFailures.push(`${theme}: unknown token in pair ${pair.foreground}/${pair.background}`);
      continue;
    }
    const ratio = contrastRatio(fg, bg);
    if (ratio < pair.minRatio) {
      contrastFailures.push(
        `${theme}: ${pair.foreground} on ${pair.background} is ${ratio.toFixed(2)}:1, needs ${pair.minRatio}:1`,
      );
    }
  }
}

if (contrastFailures.length) {
  for (const failure of contrastFailures) console.error(`FAIL contrast ${failure}`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Swift
// ---------------------------------------------------------------------------

const camel = (value) => value.replace(/[-_](.)/g, (_, c) => c.toUpperCase());
const screaming = (value) =>
  value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[-\s]/g, "_").toUpperCase();

function swiftColor(hex) {
  const raw = hex.replace("#", "");
  const hasAlpha = raw.length === 8;
  const [r, g, b] = parseHex(hex).map((v) => (v / 255).toFixed(4));
  const a = hasAlpha ? (parseInt(raw.slice(6, 8), 16) / 255).toFixed(4) : "1.0000";
  return `Color(.sRGB, red: ${r}, green: ${g}, blue: ${b}, opacity: ${a})`;
}

function buildSwift() {
  const out = HEADER.map((line) => `// ${line}`);
  out.push("", "import SwiftUI", "");
  out.push("/// Canonical Faithful design tokens.");
  out.push("///");
  out.push("/// Values come from `design/faithful/tokens.json`. Editing them here has no");
  out.push("/// effect beyond the next regeneration, and CI fails on drift.");
  out.push("public enum FaithfulTokens {");
  out.push(`    public static let version = "${tokens.version}"`);
  out.push("");

  out.push("    public struct Palette: Sendable {");
  for (const key of Object.keys(tokens.color.light)) {
    out.push(`        public let ${key}: Color`);
  }
  out.push("    }");
  out.push("");

  for (const theme of ["light", "dark"]) {
    out.push(`    public static let ${theme} = Palette(`);
    const palette = tokens.color[theme];
    out.push(
      Object.entries(palette)
        .map(([key, hex]) => `        ${key}: ${swiftColor(hex)}`)
        .join(",\n"),
    );
    out.push("    )");
    out.push("");
  }

  out.push("    public enum Spacing {");
  for (const [key, value] of Object.entries(tokens.spacing)) {
    out.push(`        public static let ${camel(key)}: CGFloat = ${value}`);
  }
  out.push("    }");
  out.push("");

  out.push("    public enum Radius {");
  for (const [key, value] of Object.entries(tokens.radius)) {
    out.push(`        public static let ${camel(key)}: CGFloat = ${value}`);
  }
  out.push("    }");
  out.push("");

  out.push("    public enum Layout {");
  for (const [key, value] of Object.entries(tokens.layout)) {
    out.push(`        public static let ${camel(key)}: CGFloat = ${value}`);
  }
  out.push("    }");
  out.push("");

  out.push("    public enum BorderWidth {");
  for (const [key, value] of Object.entries(tokens.border)) {
    out.push(`        public static let ${camel(key)}: CGFloat = ${value}`);
  }
  out.push("    }");
  out.push("");

  out.push("    public enum IconSize {");
  for (const [key, value] of Object.entries(tokens.icon)) {
    out.push(`        public static let ${camel(key)}: CGFloat = ${value}`);
  }
  out.push("    }");
  out.push("");

  out.push("    public enum TouchTarget {");
  for (const [key, value] of Object.entries(tokens.touchTarget)) {
    if (typeof value === "number") {
      out.push(`        public static let ${camel(key)}: CGFloat = ${value}`);
    }
  }
  out.push("    }");
  out.push("");

  out.push("    public struct TextRole: Sendable {");
  out.push("        public let size: CGFloat");
  out.push("        public let lineHeight: CGFloat");
  out.push("        public let weight: Font.Weight");
  out.push("        public let tracking: CGFloat");
  out.push("        public let isDisplay: Bool");
  out.push("    }");
  out.push("");
  out.push("    public enum Text {");
  for (const [role, spec] of Object.entries(tokens.typography.roles)) {
    const weight =
      spec.weight >= 700 ? "bold" : spec.weight >= 600 ? "semibold" : spec.weight >= 500 ? "medium" : "regular";
    out.push(
      `        public static let ${camel(role)} = TextRole(size: ${spec.size}, lineHeight: ${spec.lineHeight}, weight: .${weight}, tracking: ${spec.tracking.toFixed(2)}, isDisplay: ${spec.family === "display"})`,
    );
  }
  out.push("    }");
  out.push("");

  out.push("    public enum Motion {");
  for (const [key, value] of Object.entries(tokens.motion.duration)) {
    out.push(`        public static let ${camel(key)}: Double = ${(value / 1000).toFixed(3)}`);
  }
  out.push(
    `        public static let reducedMotionDuration: Double = ${(tokens.motion.reducedMotion.durationOverride / 1000).toFixed(3)}`,
  );
  out.push("    }");
  out.push("");

  out.push("    public enum Elevation {");
  for (const [key, spec] of Object.entries(tokens.elevation)) {
    if (typeof spec !== "object") continue;
    out.push(
      `        public static let ${camel(key)} = (y: CGFloat(${spec.y}), blur: CGFloat(${spec.blur}), opacity: ${spec.opacity})`,
    );
  }
  out.push("    }");
  out.push("}");

  return `${out.join("\n")}\n`;
}

// ---------------------------------------------------------------------------
// Kotlin
// ---------------------------------------------------------------------------

function kotlinColor(hex) {
  const raw = hex.replace("#", "");
  const argb = raw.length === 8 ? raw.slice(6, 8) + raw.slice(0, 6) : `FF${raw}`;
  return `Color(0x${argb.toUpperCase()})`;
}

function buildKotlin() {
  const out = HEADER.map((line) => `// ${line}`);
  out.push("");
  out.push("package io.faithform.faithful.design");
  out.push("");
  out.push("import androidx.compose.ui.graphics.Color");
  out.push("import androidx.compose.ui.text.font.FontWeight");
  out.push("import androidx.compose.ui.unit.dp");
  out.push("import androidx.compose.ui.unit.sp");
  out.push("import androidx.compose.ui.unit.Dp");
  out.push("import androidx.compose.ui.unit.TextUnit");
  out.push("");
  out.push("/**");
  out.push(" * Canonical Faithful design tokens.");
  out.push(" *");
  out.push(" * Values come from `design/faithful/tokens.json`. Editing them here has no");
  out.push(" * effect beyond the next regeneration, and CI fails on drift.");
  out.push(" */");
  out.push("object FaithfulTokens {");
  out.push(`    const val VERSION = "${tokens.version}"`);
  out.push("");

  out.push("    data class Palette(");
  out.push(
    Object.keys(tokens.color.light)
      .map((key) => `        val ${key}: Color`)
      .join(",\n"),
  );
  out.push("    )");
  out.push("");

  for (const theme of ["light", "dark"]) {
    out.push(`    val ${theme.toUpperCase()} = Palette(`);
    out.push(
      Object.entries(tokens.color[theme])
        .map(([key, hex]) => `        ${key} = ${kotlinColor(hex)}`)
        .join(",\n"),
    );
    out.push("    )");
    out.push("");
  }

  const dpBlock = (name, entries) => {
    out.push(`    object ${name} {`);
    for (const [key, value] of Object.entries(entries)) {
      if (typeof value !== "number") continue;
      out.push(`        val ${camel(key)}: Dp = ${value}.dp`);
    }
    out.push("    }");
    out.push("");
  };

  dpBlock("Spacing", tokens.spacing);
  dpBlock("Radius", tokens.radius);
  dpBlock("Layout", tokens.layout);
  dpBlock("BorderWidth", tokens.border);
  dpBlock("IconSize", tokens.icon);
  dpBlock("TouchTarget", tokens.touchTarget);

  out.push("    data class TextRole(");
  out.push("        val size: TextUnit,");
  out.push("        val lineHeight: TextUnit,");
  out.push("        val weight: FontWeight,");
  out.push("        val trackingSp: Double,");
  out.push("        val isDisplay: Boolean");
  out.push("    )");
  out.push("");
  out.push("    object Text {");
  for (const [role, spec] of Object.entries(tokens.typography.roles)) {
    out.push(
      `        val ${camel(role)} = TextRole(${spec.size}.sp, ${spec.lineHeight}.sp, FontWeight(${spec.weight}), ${spec.tracking.toFixed(2)}, ${spec.family === "display"})`,
    );
  }
  out.push("    }");
  out.push("");

  out.push("    object Motion {");
  for (const [key, value] of Object.entries(tokens.motion.duration)) {
    out.push(`        const val ${screaming(key)}_MS = ${value}`);
  }
  out.push(
    `        const val REDUCED_MOTION_MS = ${tokens.motion.reducedMotion.durationOverride}`,
  );
  out.push("    }");
  out.push("");

  out.push("    object Elevation {");
  for (const [key, spec] of Object.entries(tokens.elevation)) {
    if (typeof spec !== "object") continue;
    out.push(`        val ${camel(key)}Y: Dp = ${spec.y}.dp`);
    out.push(`        val ${camel(key)}Blur: Dp = ${spec.blur}.dp`);
    out.push(`        const val ${screaming(key)}_OPACITY = ${spec.opacity.toFixed(2)}f`);
  }
  out.push("    }");
  out.push("}");

  return `${out.join("\n")}\n`;
}

const artifacts = [
  {
    path: "apps/faithful-ios/Sources/FaithfulKit/Generated/DesignTokens.swift",
    content: buildSwift(),
  },
  {
    path:
      "apps/faithful-android/core/design/src/main/kotlin/io/faithform/faithful/design/DesignTokens.kt",
    content: buildKotlin(),
  },
];

const stale = [];
for (const artifact of artifacts) {
  const full = join(ROOT, artifact.path);
  if (CHECK) {
    if (!existsSync(full) || readFileSync(full, "utf8") !== artifact.content) {
      stale.push(artifact.path);
    }
  } else {
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, artifact.content, "utf8");
  }
}

const pairCount = tokens.contrast.pairs.length * 2;

if (CHECK) {
  if (stale.length) {
    for (const path of stale) console.error(`FAIL stale generated tokens: ${path}`);
    console.error("Run `pnpm design:generate` and commit the result.");
    process.exit(1);
  }
  console.log(`Design tokens current; ${pairCount} contrast pairs pass WCAG minimums.`);
} else {
  for (const artifact of artifacts) console.log(`wrote ${artifact.path}`);
  console.log(`${pairCount} contrast pairs pass WCAG minimums.`);
}
