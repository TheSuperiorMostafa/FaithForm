#!/usr/bin/env node
/**
 * Generates the Faithful mobile contract from the authoritative Zod schemas in
 * lib/mobile/v1/contract.ts.
 *
 * Outputs, all committed:
 *   contracts/faithful/v1/schema.json                       — JSON Schema 2020-12
 *   apps/faithful-ios/Sources/FaithfulKit/Generated/Contract.swift
 *   apps/faithful-android/core/contract/src/main/kotlin/.../Contract.kt
 *
 * Run with --check to verify the committed output is current without writing.
 * CI uses --check so a contract change that skips regeneration fails the build
 * rather than silently shipping three disagreeing definitions.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";

const CHECK = process.argv.includes("--check");
const ROOT = process.cwd();

const { CONTRACT_SCHEMAS, CONTRACT_ENUMS } = await import(
  "../lib/mobile/v1/contract.ts"
).catch(async () => import(join(ROOT, "lib/mobile/v1/contract.ts")));

const { z } = await import("zod");

const HEADER_LINES = [
  "Generated by scripts/generate-contract.mjs — do not edit by hand.",
  "Source of truth: lib/mobile/v1/contract.ts",
  "Regenerate with: pnpm contract:generate",
];

// ---------------------------------------------------------------------------
// JSON Schema
// ---------------------------------------------------------------------------

function buildJsonSchema() {
  const definitions = {};
  for (const [name, schema] of Object.entries(CONTRACT_SCHEMAS)) {
    definitions[name] = z.toJSONSchema(schema, { io: "output" });
  }
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://faithform.io/contracts/faithful/v1/schema.json",
    title: "Faithful mobile contract v1",
    description: HEADER_LINES.join(" "),
    $defs: definitions,
  };
}

// ---------------------------------------------------------------------------
// Shared type walking
// ---------------------------------------------------------------------------

/**
 * Resolves one JSON Schema node to a native type name.
 *
 * Deliberately narrow: it understands only the constructs the contract
 * actually uses. An unsupported construct throws rather than emitting
 * something plausible, so the failure surfaces at generation time.
 */
function nativeType(node, lang, context) {
  if (!node || typeof node !== "object") {
    throw new Error(`${context}: empty schema node`);
  }

  if (node.anyOf || node.oneOf) {
    const variants = node.anyOf ?? node.oneOf;
    const nonNull = variants.filter((v) => v.type !== "null");
    if (nonNull.length !== 1) {
      throw new Error(`${context}: only nullable unions are supported`);
    }
    return { type: nativeType(nonNull[0], lang, context).type, optional: true };
  }

  if (node.const !== undefined) {
    // The type comes from the constant's own type.
    //
    // This used to return `Bool` for *every* const, which happened to be right
    // because the only consts in the contract were `ok: true` on the success
    // and failure envelopes. Prompt 9 added the first `z.literal("recording")`,
    // and the generator silently emitted `Bool` for a string — producing a
    // Swift and Kotlin type that compiled and then failed to decode at run
    // time. Found by a fixture test, not by reading.
    const constType = typeof node.const;
    if (constType === "boolean") {
      return { type: lang === "swift" ? "Bool" : "Boolean", optional: false };
    }
    if (constType === "string") return { type: "String", optional: false };
    if (constType === "number") {
      return {
        type: Number.isInteger(node.const) ? "Int" : "Double",
        optional: false,
      };
    }
    throw new Error(`${context}: unsupported const type ${constType}`);
  }

  if (node.enum) {
    return { type: lang === "swift" ? "String" : "String", optional: false };
  }

  switch (node.type) {
    case "string":
      return { type: "String", optional: false };
    case "boolean":
      return { type: lang === "swift" ? "Bool" : "Boolean", optional: false };
    case "integer":
      return { type: "Int", optional: false };
    case "number":
      return { type: lang === "swift" ? "Double" : "Double", optional: false };
    case "array": {
      const inner = nativeType(node.items, lang, `${context}[]`);
      const wrapped = inner.optional
        ? lang === "swift"
          ? `${inner.type}?`
          : `${inner.type}?`
        : inner.type;
      return {
        type: lang === "swift" ? `[${wrapped}]` : `List<${wrapped}>`,
        optional: false,
      };
    }
    case "object": {
      if (node.additionalProperties && typeof node.additionalProperties === "object") {
        const value = nativeType(node.additionalProperties, lang, `${context}{}`);
        return {
          type:
            lang === "swift"
              ? `[String: ${value.type}]`
              : `Map<String, ${value.type}>`,
          optional: false,
        };
      }
      throw new Error(`${context}: inline objects must be named schemas`);
    }
    case "null":
      return { type: "String", optional: true };
    default:
      throw new Error(`${context}: unsupported type ${JSON.stringify(node.type)}`);
  }
}

/** Named schemas are emitted as their own type and referenced by name. */
function resolveRef(node, names) {
  const ref = node?.$ref;
  if (!ref) return null;
  const name = ref.split("/").pop();
  return names.includes(name) ? name : null;
}

function fieldsOf(schemaNode, names, lang, typeName) {
  const required = new Set(schemaNode.required ?? []);
  const properties = schemaNode.properties ?? {};
  return Object.entries(properties).map(([key, node]) => {
    const refName = resolveRef(node, names);
    let type;
    let optional;

    if (refName) {
      type = refName;
      optional = false;
    } else if (node.anyOf || node.oneOf) {
      const variants = (node.anyOf ?? node.oneOf).filter((v) => v.type !== "null");
      const innerRef = variants.length === 1 ? resolveRef(variants[0], names) : null;
      if (innerRef) {
        type = innerRef;
        optional = true;
      } else {
        const resolved = nativeType(node, lang, `${typeName}.${key}`);
        type = resolved.type;
        optional = resolved.optional;
      }
    } else if (node.type === "array" && resolveRef(node.items ?? {}, names)) {
      const inner = resolveRef(node.items, names);
      type = lang === "swift" ? `[${inner}]` : `List<${inner}>`;
      optional = false;
    } else {
      const resolved = nativeType(node, lang, `${typeName}.${key}`);
      type = resolved.type;
      optional = resolved.optional;
    }

    if (!required.has(key)) optional = true;
    return { key, type, optional };
  });
}

// ---------------------------------------------------------------------------
// Swift
// ---------------------------------------------------------------------------

function buildSwift(jsonSchema) {
  const names = Object.keys(jsonSchema.$defs);
  const out = [];
  out.push(...HEADER_LINES.map((line) => `// ${line}`));
  out.push("");
  out.push("import Foundation");
  out.push("");

  for (const [name, values] of Object.entries(CONTRACT_ENUMS)) {
    out.push("/// Forward-compatible: an unrecognised value decodes to `.unknown`");
    out.push("/// rather than failing, so a server that adds a case cannot break a");
    out.push("/// released build.");
    out.push(`public enum ${name}: RawRepresentable, Codable, Hashable, Sendable {`);
    for (const value of values) {
      out.push(`    case ${swiftCase(value)}`);
    }
    out.push("    case unknown(String)");
    out.push("");
    out.push("    public init(rawValue: String) {");
    out.push("        switch rawValue {");
    for (const value of values) {
      out.push(`        case "${value}": self = .${swiftCase(value)}`);
    }
    out.push("        default: self = .unknown(rawValue)");
    out.push("        }");
    out.push("    }");
    out.push("");
    out.push("    public var rawValue: String {");
    out.push("        switch self {");
    for (const value of values) {
      out.push(`        case .${swiftCase(value)}: return "${value}"`);
    }
    out.push("        case let .unknown(value): return value");
    out.push("        }");
    out.push("    }");
    out.push("");
    out.push("    public init(from decoder: Decoder) throws {");
    out.push("        let container = try decoder.singleValueContainer()");
    out.push("        self.init(rawValue: try container.decode(String.self))");
    out.push("    }");
    out.push("");
    out.push("    public func encode(to encoder: Encoder) throws {");
    out.push("        var container = encoder.singleValueContainer()");
    out.push("        try container.encode(rawValue)");
    out.push("    }");
    out.push("}");
    out.push("");
  }

  for (const name of names) {
    const node = jsonSchema.$defs[name];
    const fields = fieldsOf(node, names, "swift", name);
    out.push("/// Unknown additive fields are ignored by Codable, which is what lets a");
    out.push("/// released client keep working when the server adds one.");
    out.push(`public struct ${name}: Codable, Hashable, Sendable {`);
    for (const field of fields) {
      const type = enumOverride(name, field.key, "swift") ?? field.type;
      out.push(`    public let ${field.key}: ${type}${field.optional ? "?" : ""}`);
    }
    out.push("");
    out.push(`    public init(`);
    out.push(
      fields
        .map((field) => {
          const type = enumOverride(name, field.key, "swift") ?? field.type;
          return `        ${field.key}: ${type}${field.optional ? "? = nil" : ""}`;
        })
        .join(",\n"),
    );
    out.push("    ) {");
    for (const field of fields) {
      out.push(`        self.${field.key} = ${field.key}`);
    }
    out.push("    }");
    out.push("}");
    out.push("");
  }

  return out.join("\n");
}

/**
 * Swift keywords that can legitimately appear as a wire enum value.
 * A case named `public` is valid Swift only when escaped, and silently
 * renaming it would break the mapping to the wire value.
 */
const SWIFT_RESERVED = new Set([
  "public", "private", "internal", "open", "default", "class", "struct",
  "enum", "protocol", "extension", "import", "return", "case", "where",
  "self", "static", "let", "var", "func", "if", "else", "for", "in",
  "repeat", "true", "false", "nil", "operator", "subscript", "init", "deinit",
  "associatedtype", "typealias", "throws", "rethrows", "try", "catch", "defer",
  "guard", "switch", "break", "continue", "fallthrough", "while", "as", "is",
  "any", "some", "inout", "indirect", "lazy", "final", "required", "optional",
]);

function swiftCase(value) {
  const parts = value.split("_");
  const camel =
    parts[0] +
    parts
      .slice(1)
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join("");
  return SWIFT_RESERVED.has(camel) ? `\`${camel}\`` : camel;
}

/**
 * Which struct fields are enums rather than plain strings. Zod erases that at
 * the JSON Schema level for `z.enum`, so the mapping is stated once here.
 */
const ENUM_FIELDS = {
  "VisitorProfile.status": "AccountStatus",
  "VisitorProfile.autoAttendanceConsent": "ConsentState",
  "ChurchRelationship.state": "RelationshipState",
  "ChurchRelationship.joinPolicy": "JoinPolicy",
  "AccountRequest.kind": "AccountRequestKind",
  "AccountRequest.status": "AccountRequestStatus",
  "ErrorBody.code": "MobileErrorCode",
  "AccountActionRequest.kind": "AccountRequestKind",
  "DiscoveredChurch.joinPolicy": "JoinPolicy",
  "ChurchProfile.joinPolicy": "JoinPolicy",
  "ChurchProfile.relationshipState": "RelationshipState",
  "FeedItem.visibility": "AnnouncementVisibility",
  "NotificationPreference.topic": "NotificationTopic",
  "SetPreferenceRequest.topic": "NotificationTopic",
  "DeviceInstallation.platform": "DevicePlatform",
  "RegisterDeviceRequest.platform": "DevicePlatform",
  "AttendanceCapability.autoAttendanceConsent": "ConsentState",
  "AttendanceResult.outcome": "AttendanceOutcome",
  "AttendanceStatus.source": "AttendanceSource",
  "AttendanceHistoryItem.source": "AttendanceSource",
};

function enumOverride(typeName, key) {
  return ENUM_FIELDS[`${typeName}.${key}`] ?? null;
}

// ---------------------------------------------------------------------------
// Kotlin
// ---------------------------------------------------------------------------

function buildKotlin(jsonSchema) {
  const names = Object.keys(jsonSchema.$defs);
  const out = [];
  out.push(...HEADER_LINES.map((line) => `// ${line}`));
  out.push("");
  out.push("package io.faithform.faithful.contract");
  out.push("");
  out.push("import kotlinx.serialization.SerialName");
  out.push("import kotlinx.serialization.Serializable");
  out.push("");

  for (const [name, values] of Object.entries(CONTRACT_ENUMS)) {
    out.push("/**");
    out.push(" * Forward-compatible: an unrecognised value decodes to [UNKNOWN] rather than");
    out.push(" * throwing, so a server that adds a case cannot break a released build.");
    out.push(" */");
    out.push("@Serializable");
    out.push(`enum class ${name} {`);
    for (const value of values) {
      out.push(`    @SerialName("${value}") ${value.toUpperCase()},`);
    }
    out.push("    UNKNOWN;");
    out.push("");
    out.push("    companion object {");
    out.push(`        fun fromWire(value: String?): ${name} =`);
    out.push("            entries.firstOrNull { it.wire == value } ?: UNKNOWN");
    out.push("    }");
    out.push("");
    out.push("    val wire: String");
    out.push("        get() = when (this) {");
    for (const value of values) {
      out.push(`            ${value.toUpperCase()} -> "${value}"`);
    }
    out.push('            UNKNOWN -> "unknown"');
    out.push("        }");
    out.push("}");
    out.push("");
  }

  for (const name of names) {
    const node = jsonSchema.$defs[name];
    const fields = fieldsOf(node, names, "kotlin", name);
    out.push("/**");
    out.push(" * Unknown additive fields are ignored by the configured Json instance,");
    out.push(" * which is what lets a released client keep working when the server adds one.");
    out.push(" */");
    out.push("@Serializable");
    out.push(`data class ${name}(`);
    out.push(
      fields
        .map((field) => {
          const type = enumOverride(name, field.key) ?? field.type;
          const suffix = field.optional ? "? = null" : "";
          return `    val ${field.key}: ${type}${suffix}`;
        })
        .join(",\n"),
    );
    out.push(")");
    out.push("");
  }

  return out.join("\n");
}

// ---------------------------------------------------------------------------
// Emit
// ---------------------------------------------------------------------------

const jsonSchema = buildJsonSchema();

const artifacts = [
  {
    path: "contracts/faithful/v1/schema.json",
    content: `${JSON.stringify(jsonSchema, null, 2)}\n`,
  },
  {
    path: "apps/faithful-ios/Sources/FaithfulKit/Generated/Contract.swift",
    content: `${buildSwift(jsonSchema)}\n`,
  },
  {
    path:
      "apps/faithful-android/core/contract/src/main/kotlin/io/faithform/faithful/contract/Contract.kt",
    content: `${buildKotlin(jsonSchema)}\n`,
  },
];

let stale = [];
for (const artifact of artifacts) {
  const full = join(ROOT, artifact.path);
  if (CHECK) {
    if (!existsSync(full) || readFileSync(full, "utf8") !== artifact.content) {
      stale.push(artifact.path);
    }
  } else {
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, artifact.content, "utf8");
  }
}

if (CHECK) {
  if (stale.length) {
    for (const path of stale) console.error(`FAIL stale generated contract: ${path}`);
    console.error("Run `pnpm contract:generate` and commit the result.");
    process.exit(1);
  }
  console.log(`Contract is current across ${artifacts.length} generated artifacts.`);
} else {
  for (const artifact of artifacts) console.log(`wrote ${artifact.path}`);
}
